const ROOT = join(import.meta.dirname, '..', '..', '..');
const walk = (d: string): string[] =>
  readdirSync(d)
    .flatMap((n) => {
      const p = join(d, n);
      return statSync(p).isDirectory() ? walk(p) : p.endsWith('.yaml') ? [p] : [];
    })
    .sort();
const readPack = (name: string): SourceFile[] => walk(join(ROOT, 'packs', name)).map((p) => ({ path: relative(ROOT, p), text: readFileSync(p, 'utf8') }));
const REPO = [...readPack('srd-5.2.1'), ...readPack('test')];

function loadOk(files: readonly SourceFile[]): Content {
  const r = loadContent(files);
  if (!r.content) throw new Error(r.errors.map(formatDiag).join('\n'));
  return r.content;
}
const messages = (r: LoadResult) => r.errors.map(formatDiag);
const tplHash = (t: CompiledTemplate | undefined): string => hash64(canonicalJson(t ?? null));
/** The repo packs with files added or replaced by path. */
const withFiles = (extra: Record<string, string>): SourceFile[] => [
  ...REPO.filter((f) => !Object.hasOwn(extra, f.path)),
  ...Object.entries(extra).map(([path, text]) => ({ path, text })),
];
const repoText = (path: string): string => REPO.find((f) => f.path === path)!.text;

