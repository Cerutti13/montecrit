function duel(features: string[], decider = 'random-legal'): FightSetup {
  const fighter = `${repoText(FIGHTER)}features: [${features.join(', ')}]\n`;
  const content = loadOk(withFiles({ ...KIT, [FIGHTER]: fighter }));
  const doc = {
    kind: 'scenario', id: 'duel', name: 'Duel', rules: '2024', packs: ['srd-5.2.1', 'test'],
    grid: { w: 6, h: 3 },
    units: [
      { seat: 'pc1', team: 'party', use: 'test:sample-fighter', at: 'B2', decider },
      { seat: 'dummy', team: 'enemies', use: 'test:training-dummy', at: 'E2' },
    ],
  };
  const r = resolveScenario(doc, 'duel.yaml', content);
  if (!r.setup) throw new Error(r.errors.map(formatDiag).join('\n'));
  return r.setup;
}

/** The PC's seat index (seats are ordered by seat id). */
const pcOf = (setup: FightSetup): number => setup.seats.findIndex((x) => x.seat === 'pc1');
const pcTpl = (setup: FightSetup): CompiledTemplate => setup.seats[pcOf(setup)]!.tpl;

function fight(setup: FightSetup, seed: number) {
  const sink = new ArraySink();
  let end: GameState | null = null;
  runFight(setup, seed, 0, makeDeciders(setup), sink, { inspect: (st) => (end = st) });
  return { events: sink.events as readonly GameEvent[], end: end! as GameState };
}

describe('free cost and perTurn (2.4)', () => {
  it('a free once-per-turn activation spends no action economy and is offered at most once per turn', () => {
    const setup = duel(['test:quick-guard']);
    expect(pcTpl(setup).features[0]!.activate).toMatchObject({ cost: 'free', pool: -1, perTurn: true });
    const pc = pcOf(setup);
    let used = 0;
    let withAction = 0;
    for (let seed = 0; seed < 40; seed++) {
      const { events } = fight(setup, seed);
      const perTurn = new Map<string, number>();
      const attacked = new Set<string>();
      for (const e of events) {
        const key = `${e.round}:${e.turnOf}`;
        if (e.k === 'attack' && e.att === pc && e.turnOf === pc) attacked.add(key);
        if (e.k !== 'act' || e.via !== 'test:quick-guard') continue;
        perTurn.set(key, (perTurn.get(key) ?? 0) + 1);
        used++;
      }
      for (const n of perTurn.values()) expect(n).toBe(1);
      for (const key of perTurn.keys()) if (attacked.has(key)) withAction++;
    }
    expect(used).toBeGreaterThan(0);
    expect(withAction).toBeGreaterThan(0); // it left the Attack action to take in the same turn
  });
});

