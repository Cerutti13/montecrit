const SHA40 = 'a'.repeat(40);
const SHA64 = 'b'.repeat(64);
const PROVENANCE = `provenance: { source: foundry-dnd5e, ref: ${SHA40}, path: packs/x.yml, foreignId: abc, recordSha256: ${SHA64}, importer: 1, review: auto }\n`;

describe('provenance (2.1)', () => {
  it('provenance is metadata: it changes the content hash but never a compiled template', () => {
    const path = 'packs/test/monsters/sniper.yaml';
    const base = loadOk(REPO);
    const marked = loadOk(withFiles({ [path]: `${repoText(path)}\n${PROVENANCE}` }));
    expect(tplHash(marked.get('test:sniper'))).toBe(tplHash(base.get('test:sniper')));
    expect(marked.hash).not.toBe(base.hash);
  });

  it('provenance is strict: a short commit ref is a load error', () => {
    const path = 'packs/test/monsters/sniper.yaml';
    const r = loadContent(withFiles({ [path]: `${repoText(path)}\n${PROVENANCE.replace(SHA40, 'abc123')}` }));
    expect(r.content).toBeNull();
    expect(messages(r).join('\n')).toMatch(/expected a full 40-character commit sha/);
  });
});

