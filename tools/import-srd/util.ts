// Shared helpers for the SRD importer (docs/design/m3.md section 4): paths, hashing,
// ordering and canonical data. Tool-time code, but it still sorts with < and > only, so
// every output is byte-stable.

import { createHash } from 'node:crypto';
import { homedir, platform } from 'node:os';
import { isAbsolute, join, relative, resolve, sep } from 'node:path';

export const REPO_ROOT = resolve(import.meta.dirname, '..', '..');
export const IMPORT_DIR = join(REPO_ROOT, 'tools', 'import-srd');
export const PACK_DIR = join(REPO_ROOT, 'packs', 'srd-5.2.1');
export const OVERRIDES_DIR = join(IMPORT_DIR, 'overrides');

/** The importer's version: provenance.importer and IMPORT.json. Bump it when output changes for a tool reason. */
export const IMPORTER_VERSION = 1;

export const GENERATED_HEADER = '# GENERATED by tools/import-srd; edit tools/import-srd/overrides/ instead';

export const byString = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

export function sha256(data: string | Uint8Array): string {
  return createHash('sha256').update(data).digest('hex');
}

/** Posix-style path relative to the repo root (for provenance, logs and IMPORT.json). */
export function repoRel(abs: string): string {
  return relative(REPO_ROOT, abs).split(sep).join('/');
}

/** True when `child` is `parent` or inside it (lexical; both resolved first). */
export function isInside(child: string, parent: string): boolean {
  const r = relative(resolve(parent), resolve(child));
  return r === '' || (!r.startsWith('..') && !isAbsolute(r));
}

/**
 * The import cache: $XDG_CACHE_HOME/montecrit/import, else ~/Library/Caches/montecrit/import on
 * macOS (~/.cache/montecrit/import elsewhere). Never the repo and never the private home
 * (~/.montecrit or $MONTECRIT_HOME): those are refused by path alone, nothing there is read.
 */
export function cacheRoot(env: NodeJS.ProcessEnv = process.env): string {
  const xdg = env.XDG_CACHE_HOME;
  const base = xdg && isAbsolute(xdg) ? xdg : platform() === 'darwin' ? join(homedir(), 'Library', 'Caches') : join(homedir(), '.cache');
  const dir = resolve(base, 'montecrit', 'import');
  assertCacheDir(dir, env);
  return dir;
}

export function assertCacheDir(dir: string, env: NodeJS.ProcessEnv = process.env): void {
  const banned = [join(homedir(), '.montecrit')];
  if (env.MONTECRIT_HOME) banned.push(env.MONTECRIT_HOME);
  if (isInside(dir, REPO_ROOT)) throw new Error(`import cache ${dir} is inside the repo; set XDG_CACHE_HOME elsewhere`);
  for (const b of banned) {
    if (isInside(dir, b) || isInside(b, dir)) throw new Error(`import cache ${dir} overlaps the private home ${b}; set XDG_CACHE_HOME elsewhere`);
  }
}

export interface CachePaths {
  readonly root: string;
  readonly foundryTgz: string;
  /** The extracted tree's parent; the tree itself is <foundryDir>/tree. */
  readonly foundryDir: string;
  readonly foundryTree: string;
  readonly pdf: string;
  readonly open5eDir: string;
  readonly bitsDir: string;
  /** drops.json, remap.json, quarantine.json: cache only, never the repo (C5). */
  readonly logsDir: string;
}

export function cachePaths(root: string = cacheRoot()): CachePaths {
  return {
    root,
    foundryTgz: join(root, 'foundry', 'src.tgz'),
    foundryDir: join(root, 'foundry'),
    foundryTree: join(root, 'foundry', 'tree'),
    pdf: join(root, 'pdf', 'srd.pdf'),
    open5eDir: join(root, 'open5e'),
    bitsDir: join(root, 'bits'),
    logsDir: join(root, 'logs'),
  };
}

/** A deep copy with every object's keys in < order; undefined values dropped. Arrays keep their order. */
export function sortDeep(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(sortDeep);
  if (v !== null && typeof v === 'object') {
    const o = v as Record<string, unknown>;
    const out: Record<string, unknown> = {};
    for (const k of Object.keys(o).sort(byString)) {
      if (o[k] !== undefined) out[k] = sortDeep(o[k]);
    }
    return out;
  }
  return v;
}

/** JSON with sorted keys, 2-space indent and a trailing newline. */
export function stableJson(v: unknown): string {
  return `${JSON.stringify(sortDeep(v), null, 2)}\n`;
}

export function isRecord(v: unknown): v is Record<string, unknown> {
  return v !== null && typeof v === 'object' && !Array.isArray(v);
}

/** Read a dotted path out of plain data; undefined when any step is missing. */
export function getPath(v: unknown, path: string): unknown {
  let cur: unknown = v;
  for (const seg of path.split('.')) {
    if (!isRecord(cur)) return undefined;
    cur = cur[seg];
  }
  return cur;
}
